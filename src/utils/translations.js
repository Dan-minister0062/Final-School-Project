// Get announcement title translation
export const getAnnouncementTitle = (key, language) => {
  const title = translations[language]?.['announcement_titles']?.[key];
  if (title) return title;
  // Fallback to English
  const fallbackTitle = translations['en']?.['announcement_titles']?.[key];
  if (fallbackTitle) return fallbackTitle;
  return key;
};

// Get announcement content translation
export const getAnnouncementContent = (key, language) => {
  const content = translations[language]?.['announcement_contents']?.[key];
  if (content) return content;
  // Fallback to English
  const fallbackContent = translations['en']?.['announcement_contents']?.[key];
  if (fallbackContent) return fallbackContent;
  return key;
};

// Get complete announcement translation (both title and content)
export const getAnnouncementTranslation = (key, language) => {
  return {
    title: getAnnouncementTitle(key, language),
    content: getAnnouncementContent(key, language)
  };
};

// Get translated announcement for display with fallback
export const getTranslatedAnnouncement = (key, language, customTitle, customContent) => {
  // If custom content is provided, use it directly
  if (customTitle && customContent) {
    return { title: customTitle, content: customContent };
  }
  
  // Otherwise try to get translation
  return getAnnouncementTranslation(key, language);
};

// Get all announcement keys
export const getAnnouncementKeys = (language = 'en') => {
  const titles = translations[language]?.['announcement_titles'] || {};
  return Object.keys(titles);
};

// Get all announcements as array
export const getAllAnnouncements = (language = 'en') => {
  const titles = translations[language]?.['announcement_titles'] || {};
  const contents = translations[language]?.['announcement_contents'] || {};
  
  return Object.keys(titles).map(key => ({
    id: key,
    title: titles[key] || key,
    content: contents[key] || key
  }));
};

// Check if announcement translation exists
export const hasAnnouncementTranslation = (key, language) => {
  return !!(translations[language]?.['announcement_titles']?.[key]);
};

// Get translated announcement for a specific announcement object
export const translateAnnouncement = (announcement, language) => {
  // If announcement has translation key
  if (announcement.translationKey) {
    const translated = getAnnouncementTranslation(announcement.translationKey, language);
    return {
      ...announcement,
      title: translated.title,
      content: translated.content
    };
  }
  
  // If announcement has translations object
  if (announcement.translations) {
    const translated = announcement.translations[language] || announcement.translations['en'] || announcement;
    return {
      ...announcement,
      title: translated.title || announcement.title,
      content: translated.content || announcement.content
    };
  }
  
  // Return as-is
  return announcement;
};